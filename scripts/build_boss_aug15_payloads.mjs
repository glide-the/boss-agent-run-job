function parseJsonl(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => JSON.parse(line));
}

function firstLine(v) {
  return String(v || '').split('\n')[0].trim();
}

function toText(v) {
  if (Array.isArray(v)) return v.join('、');
  if (v === undefined || v === null) return '未提及';
  return String(v);
}

