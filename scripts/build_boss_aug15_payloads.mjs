function normalizeFocusValue(value) {
  if (validFocusValues.has(value)) return value;
  if (value === '学历核验') return '其他';
  if (value === '团队配置') return '团队目标';
  if (value === '业务经验') return '行业经验';
  return '其他';
}

function normalizeFocusList(value) {
  if (!Array.isArray(value)) return ['其他'];
  const out = value.map(normalizeFocusValue);
  return out.length ? out : ['其他'];
}

function normalizeShortboardValue(value) {
  if (value === '行业经验') return '缺行业经验';
  if (value === '方向不匹配') return '简历不匹配';
  if (value === '地域/到岗时间') return '其他';
  if (value === '外包接受度') return '其他';
  if (value === '未提及' || value === undefined || value === null) return '其他';
  return value;
}

function toRows(records, fields) {
  return {
    fields,
    rows: records.map((record) => fields.map((field) => record[field] ?? null)),
  };
}

